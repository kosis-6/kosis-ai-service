"""지역 명칭 통일 (2026-11-18): 표마다 다르게 적힌 지역 이름을 기준 지역에 잇기"""

import pytest

from pipeline.region_map import RegionIndex, Source, match_region, unmatched_reason

ROWS = [
    ("00", "전국", "전국", "전국"),
    ("41", "경기도", "시도", "경기도"),
    ("41110", "수원시", "시군구", "경기도 > 수원시"),
    ("41113", "권선구", "일반구", "경기도 > 권선구"),
    ("41194", "소사구", "일반구", "경기도 > 소사구"),
    ("41650", "포천시", "시군구", "경기도 > 포천시"),
    ("41610", "광주시", "시군구", "경기도 > 광주시"),
    ("28", "인천광역시", "시도", "인천광역시"),
    ("28710", "강화군", "시군구", "인천광역시 > 강화군"),
    ("29", "광주광역시", "시도", "광주광역시"),
    ("46", "전라남도", "시도", "전라남도"),
    ("12", "전남광주통합특별시", "시도", "전남광주통합특별시"),
    ("48", "경상남도", "시도", "경상남도"),
    ("48120", "창원시(통합)", "시군구", "경상남도 > 창원시(통합)"),
    ("48125", "마산합포구", "일반구", "경상남도 > 마산합포구"),
    ("50", "제주특별자치도", "시도", "제주특별자치도"),
    ("50110", "제주시", "시군구", "제주특별자치도 > 제주시"),
]
IDX = RegionIndex(ROWS)


def codes(name, path, level=2):
    return match_region(IDX, "999", Source("X", name, level, path))[0]


@pytest.mark.parametrize(
    "name, path, expected",
    [
        # 원래 되던 것
        ("권선구", "경기도 > 권선구", ["41113"]),
        ("권선구", "경기도 > 수원시 > 권선구", ["41113"]),
        # 일반구를 시 이름과 붙여 씀
        ("수원시 권선구", "경기도 > 수원시 권선구", ["41113"]),
        ("부천시소사구", "경기도 > 부천시소사구", ["41194"]),
        ("창원시 마산합포구", "경상남도 > 창원시 마산합포구", ["48125"]),
        # 시도 옛 이름·새 이름
        ("제주도", "제주도", ["50"]),
        ("제주시", "제주도 > 제주시", ["50110"]),
        ("광주광역시", "전남광주통합특별시 > 광주광역시", ["29"]),
        ("전라남도", "전남광주통합특별시 > 전라남도", ["46"]),
        ("통합창원시", "경상남도 > 통합창원시", ["48120"]),
        # 이름만 바뀐 옛 시군구
        ("포천군", "경기도 > 포천군", ["41650"]),
        ("포천군", "포천군", ["41650"]),
        ("광주군", "광주군", ["41610"]),
        ("강화군", "경기도 > 강화군", ["28710"]),
    ],
)
def test_matched(name, path, expected):
    assert codes(name, path) == expected


@pytest.mark.parametrize(
    "name, path",
    [
        ("남제주군", "제주특별자치도 > 남제주군"),  # 2006 합쳐짐
        ("여천시", "전라남도 > 여천시"),  # 1998 여수시로 합쳐짐
        ("마산시(변동전)", "경상남도 > 마산시(변동전)"),
        ("권선1동", "경기도 > 수원시 권선구 > 권선1동"),  # 읍면동
        ("남구", "남구"),  # 시도가 없음
    ],
)
def test_not_matched(name, path):
    assert codes(name, path) == []


def test_total():
    assert codes("총계", "총계", level=1) == ["00"]


@pytest.mark.parametrize(
    "name, reason",
    [
        ("길동", "읍·면·동 (기준 목록은 시군구까지)"),
        ("조치원읍", "읍·면·동 (기준 목록은 시군구까지)"),
        ("계룡출장소", "출장소 (기준 목록은 시군구까지)"),
        ("국   외", "국외"),
        ("미상", "지역이 아닌 분류 (기타·미상)"),
        ("동부", "지역이 아닌 동·읍·면부 분류"),
        ("남제주군", "기준 지역 목록(2008~2025 주민등록)에 없는 지역"),
    ],
)
def test_reason(name, reason):
    assert unmatched_reason(name) == reason
