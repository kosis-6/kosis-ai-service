type Props = { name: IconName; size?: number; stroke?: number; className?: string };

/** 장식용 아이콘 (스크린 리더는 읽지 않는다. 뜻은 옆의 글자나 aria-label 이 전한다) */
export function Icon({ name, size = 16, stroke = 1.5, className = "icon" }: Props) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke * (24 / size)}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}
